    @Test
    fun boostReduceBlockAndClampingFollowPlanWeights() {
        val hindi = TasteTaxonomy.byKey("hindi")!!
        val hipHop = TasteTaxonomy.byKey("rap")!!

        // Default seeded node starts neutral (45f)
        val initialWeight = TasteProfileRepository.snapshot.value.weightForTag(hindi)
        assertEquals(TasteConstants.DEFAULT_NEUTRAL_WEIGHT, initialWeight)

        // Boost adds +15f -> 60f and marks preferred
        TasteProfileRepository.boostTag(hindi)
        assertEquals(60f, TasteProfileRepository.snapshot.value.weightForTag(hindi))

        // Repeated boosts clamp at 100f
        repeat(5) { TasteProfileRepository.boostTag(hindi) }
        assertEquals(100f, TasteProfileRepository.snapshot.value.weightForTag(hindi))

        // Reduce subtracts 20f down to minimum floor 5f
        TasteProfileRepository.reduceTag(hipHop)
        assertEquals(25f, TasteProfileRepository.snapshot.value.weightForTag(hipHop))
        repeat(4) { TasteProfileRepository.reduceTag(hipHop) }
        assertEquals(5f, TasteProfileRepository.snapshot.value.weightForTag(hipHop))

        // Block sets weight to 0f and populates blocked mask
        TasteProfileRepository.blockTag(hipHop)
        val snap = TasteProfileRepository.snapshot.value
        assertTrue(snap.isTagBlocked(hipHop))
        assertEquals(0f, snap.weightForTag(hipHop))
        assertTrue((snap.blockedGenreMask and hipHop.bitMask) != 0)

        // Unblock restores neutral 45f
        TasteProfileRepository.unblockTag(hipHop)
        assertFalse(TasteProfileRepository.snapshot.value.isTagBlocked(hipHop))
        assertEquals(TasteConstants.DEFAULT_NEUTRAL_WEIGHT, TasteProfileRepository.snapshot.value.weightForTag(hipHop))
    }

    @Test
    fun passiveListenQuickSkipWeeklyDecayAndManualReorderWork() {
        val hindi = TasteTaxonomy.byKey("hindi")!!
        val pop = TasteTaxonomy.byKey("pop")!!
        val track = song(
            id = "v1234567890",
            title = "Kesariya",
            artist = "Arijit Singh",
            artistId = "UC_arijit",
        )
        val resolved = ResolvedTags(langMask = hindi.bitMask, genreMask = pop.bitMask)

        // First passive listen (>30s or >50%) auto-adds artist at 45f + 1.5f nudge
        TasteProfileRepository.recordPassiveListen(track, resolved)
        var snap = TasteProfileRepository.snapshot.value
        assertEquals(46.5f, snap.weightFor(TasteCategory.ARTIST, TasteConstants.normalizeArtistKey("UC_arijit")))
        assertEquals(46.5f, snap.weightForTag(hindi))
        assertEquals(46.5f, snap.weightForTag(pop))

        // Second passive listen nudges unpinned artist (+1.5f)
        TasteProfileRepository.recordPassiveListen(track, resolved)
        snap = TasteProfileRepository.snapshot.value
        assertEquals(48.0f, snap.weightFor(TasteCategory.ARTIST, TasteConstants.normalizeArtistKey("UC_arijit")))

        // Quick skip (<20s) deducts 1f from artist & genre
        TasteProfileRepository.recordQuickSkip(track, resolved)
        snap = TasteProfileRepository.snapshot.value
        assertEquals(47.0f, snap.weightFor(TasteCategory.ARTIST, TasteConstants.normalizeArtistKey("UC_arijit")))
        assertEquals(47.0f, snap.weightForTag(pop))

        // Manual drag-to-reorder assigns monotonic 95..15 weights and pins manualRank
        val activeLangs = TasteProfileRepository.snapshot.value.activeNodes(TasteCategory.LANGUAGE)
        val targetId = TasteTaxonomy.nodeId(hindi)
        val reordered = listOf(targetId) + activeLangs.map { it.id }.filterNot { it == targetId }
        TasteProfileRepository.reorderCategory(TasteCategory.LANGUAGE, reordered)
        snap = TasteProfileRepository.snapshot.value
        assertEquals(95f, snap.weightForTag(hindi))

        // Passive listen on manually ranked tag nudges gently (+0.5f instead of +1.5f)
        TasteProfileRepository.recordPassiveListen(track, resolved)
        assertEquals(95.5f, TasteProfileRepository.snapshot.value.weightForTag(hindi))

        // Time decay after 7 days pulls 95.5f gently toward neutral 45f (weight * 0.97 + 45 * 0.03)
        clock.addAndGet(TasteConstants.DECAY_INTERVAL_MS + 1_000L)
        val decayed = TasteProfileRepository.applyWeeklyDecayIfDue()
        assertTrue(decayed)
        val afterDecay = TasteProfileRepository.snapshot.value.weightForTag(hindi)
        assertTrue(afterDecay < 95.5f && afterDecay > 90f, "Expected gentle decay, got $afterDecay")
    }

    @Test
    fun lruCapsFeedCacheTtlAndJsonBackupRoundTrip() {
        // Fill > 3000 songs in media_tag_cache -> must cap strictly <= MAX_CACHED_SONGS
        val hindi = TasteTaxonomy.byKey("hindi")!!
        for (i in 0 until TasteConstants.MAX_CACHED_SONGS + 50) {
            clock.addAndGet(1)
            TasteProfileRepository.putMediaTags(
                entityKey = TasteConstants.songCacheKey("vid_$i"),
                langMask = hindi.bitMask,
                genreMask = 0,
                themeMask = 0,
                source = TagSource.SOURCE,
            )
        }
        TasteProfileRepository.sweepLruAndCaps()
        assertNull(TasteProfileRepository.getMediaTags(TasteConstants.songCacheKey("vid_0")))
        assertNotNull(TasteProfileRepository.getMediaTags(TasteConstants.songCacheKey("vid_${TasteConstants.MAX_CACHED_SONGS + 49}")))

        // Feed cache TTL = 45 min
        val shelf = HomeShelf(
            title = "Hindi • Hip-Hop / Rap",
            items = listOf(ShelfItem("Track", "Artist", null, "v1", null)),
        )
        TasteProfileRepository.saveFeedCache(listOf(shelf))
        assertEquals(1, TasteProfileRepository.readFeedCache(allowStale = false).size)
        clock.addAndGet(TasteConstants.FEED_CACHE_TTL_MS + 1_000L)
        assertTrue(TasteProfileRepository.readFeedCache(allowStale = false).isEmpty())
        assertEquals(1, TasteProfileRepository.readFeedCache(allowStale = true).size)

        // JSON backup round-trip preserves blocks and preferences
        TasteProfileRepository.blockArtist("Bad Artist", "UC_bad")
        TasteProfileRepository.boostTag(hindi)
        val exported = TasteProfileRepository.exportProfileJson()
        TasteProfileRepository.resetForTesting(clock = { clock.get() })
        assertFalse(TasteProfileRepository.snapshot.value.isArtistBlocked("Bad Artist", listOf("UC_bad")))
        assertTrue(TasteProfileRepository.importProfileJson(exported))
        assertTrue(TasteProfileRepository.snapshot.value.isArtistBlocked("Bad Artist", listOf("UC_bad")))
    }

    @Test
    fun tasteFilterEnforcesHardBlocksAcrossSongsItemsShelvesDialsAndMelody() = runBlocking {
        val hindi = TasteTaxonomy.byKey("hindi")!!
        val english = TasteTaxonomy.byKey("english")!!
        val bhojpuri = TasteTaxonomy.byKey("bhojpuri")!!

        TasteProfileRepository.boostTag(hindi)
        TasteProfileRepository.blockTag(bhojpuri)
        TasteProfileRepository.blockSong(song("blocked_vid", "Blocked Track", "Good Artist"))
        TasteProfileRepository.blockArtist("Blocked Artist", "UC_blk")
        TasteProfileRepository.markArtistAsAi("Fake AI Band", "UC_ai")

        val snapWhenAiOff = TasteProfileRepository.snapshot.value
        assertFalse(snapWhenAiOff.hideAiMusic)

        // When Hide AI is OFF, user-marked AI artists are NOT filtered (only blocked items are)
        val aiSong = song("ai_1", "Synth Dream", "Fake AI Band", artistId = "UC_ai")
        assertFalse(TasteFilter.isBlocked(aiSong, snapWhenAiOff))

        // Turn Hide AI Music ON -> user-marked AI artists are blocked immediately
        TasteProfileRepository.setHideAiMusic(true)
        val snap = TasteProfileRepository.snapshot.value
        assertTrue(TasteFilter.isBlocked(aiSong, snap))

        val songs = listOf(
            song("v_good", "Tum Hi Ho", "Arijit Singh", artistId = "UC_ari"),
            song("blocked_vid", "Tum Hi Ho (Remix)", "Arijit Singh"),
            song("v_bad_art", "Nice Track", "Feat", artists = listOf(ArtistRef("Blocked Artist", "UC_blk"))),
            song("v_bhojpuri", "Bhojpuri Song Hit", "Singer X"),
            aiSong,
            song("v_eng", "English Tune", "Singer Y"),
        )
        TasteProfileRepository.putMediaTags(TasteConstants.songCacheKey("v_good"), langMask = hindi.bitMask, genreMask = 0, themeMask = 0, source = TagSource.SOURCE)
        TasteProfileRepository.putMediaTags(TasteConstants.songCacheKey("v_eng"), langMask = english.bitMask, genreMask = 0, themeMask = 0, source = TagSource.SOURCE)

        val filtered = TasteFilter.filterSongs(songs, snap)
        assertEquals(listOf("v_good", "v_eng"), filtered.map { it.videoId })
        assertTrue(TasteFilter.scoreSong(songs[0], snap) > TasteFilter.scoreSong(songs.last(), snap))

        // MixesDialEngine respects TasteFilter hard blocks
        val mixes = listOf(
            ShelfItem("Good Mix", "Arijit Singh", null, null, "RD_good"),
            ShelfItem("Bad Mix", "Blocked Artist", null, null, "RD_bad", artistIds = listOf("UC_blk")),
        )
        val pickedMixes = MixesDialEngine.pickMixes(youTube = mixes, spotify = emptyList(), tasteSnapshot = snap)
        assertEquals(listOf("RD_good"), pickedMixes.mapNotNull { it.browseId })

        // MelodyEngine respects TasteFilter hard blocks
        val melodyPool = MelodyEngine.buildInitialQueue(
            seeds = MelodyEngine.SeedPool(favorites = songs),
            likeStatuses = mapOf("v_good" to LikeStatus.LIKE),
            bannedIds = emptySet(),
            skipCounts = emptyMap(),
            config = MelodyConfig(tuner = MelodyTuner(), mood = MelodyMood.MELODY),
            tasteSnapshot = snap,
        )
        assertEquals(listOf("v_good", "v_eng"), melodyPool.map { it.videoId })
    }

