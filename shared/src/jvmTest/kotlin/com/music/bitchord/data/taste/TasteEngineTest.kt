    @Test
    fun chordWaveEnginePopsInstantlyRespectsCooldownAndPurgesOnNeverOrLess() = runBlocking {
        val good1 = song("cw1", "Track 1", "Arijit Singh", artistId = "UC_1")
        val good2 = song("cw2", "Track 2", "Pritam", artistId = "UC_2")
        val bad = song("cw3", "Track 3", "Blocked Act", artistId = "UC_blk")

        val pool = listOf(good1, good2, bad)
        TasteProfileRepository.blockArtist("Blocked Act", "UC_blk")

        val snap = TasteProfileRepository.snapshot.value
        val first = ChordWaveEngine.rollNext(snapshot = snap, fallbackPoolProvider = { pool }, random = Random(1))
        assertNotNull(first)
        assertTrue(first.videoId != "cw3")

        val second = ChordWaveEngine.rollNext(snapshot = snap, fallbackPoolProvider = { pool }, random = Random(2))
        assertNotNull(second)
        // Cooldown prevents picking the exact same track while fresh alternatives remain
        assertTrue(second.videoId != first.videoId)
        assertTrue(second.videoId != "cw3")

        // Discovery sampler returns non-empty query strings
        val (query, _, _) = ChordWaveEngine.sampleBucketQuery(snap, Random(7))
        assertTrue(query.isNotBlank())
    }
